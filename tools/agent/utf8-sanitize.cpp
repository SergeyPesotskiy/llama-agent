// ---------------------------------------------------------------------------
// Plausibility scoring: Russian letter frequencies (percent of letters in a
// large Russian text corpus). Used to pick the encoding that makes invalid
// byte runs look like real text.
// ---------------------------------------------------------------------------

static const double kRuFreq[32] = { // а б в г д е ж з и й к л м н о п р с т у ф х ц ч ш щ ъ ы ь э ю я
    7.95, 1.69, 3.47, 1.63, 3.50, 8.34, 0.89, 0.50, 7.08, 0.43, 3.00, 4.26,
    2.55, 6.34, 10.97, 2.41, 4.56, 4.98, 6.01, 2.41, 0.36, 1.18, 0.45, 1.45,
    0.72, 0.55, 0.31, 1.88, 1.78, 0.27, 0.98, 1.90
};

double char_weight(uint32_t cp) {
    if (cp >= 0x0410 && cp <= 0x042F) return kRuFreq[cp - 0x0410]; // А-Я -> а-я
    if (cp >= 0x0430 && cp <= 0x044F) return kRuFreq[cp - 0x0430]; // а-я
    if (cp == 0x0401 || cp == 0x0451) return 1.2;                  // Ё ё
    if (cp >= 0x0400 && cp <= 0x04FF) return 0.6;                  // other Cyrillic
    if (cp == 0x0020 || cp == 0x00A0) return 1.0;                  // space / nbsp
    if ((cp >= 0x0030 && cp <= 0x0039) ||
        (cp >= 0x0041 && cp <= 0x005A) ||
        (cp >= 0x0061 && cp <= 0x007A)) return 1.0;                // digits / latin
    if ((cp >= 0x0021 && cp <= 0x002F) || (cp >= 0x003A && cp <= 0x0040) ||
        (cp >= 0x005B && cp <= 0x0060) || (cp >= 0x007B && cp <= 0x007E)) {
        return 0.8; // ascii punctuation
    }
    if (cp >= 0x2010 && cp <= 0x203A) return 0.8;                  // quotes, dashes, guillemets
    if (cp >= 0x00C0 && cp <= 0x00FF) return 0.5;                  // latin-1 letters
    if (cp >= 0x0080 && cp <= 0x009F) return 0.1;                  // C1 controls - suspicious
    if (cp == 0) return 0.1;                                       // undefined in that encoding
    return 0.3;                                                    // box drawing, math, misc
}

