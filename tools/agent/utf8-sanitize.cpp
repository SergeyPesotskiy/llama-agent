utf8_sanitize_result utf8_sanitize(const std::string & s) {
    utf8_sanitize_result res;
    if (s.empty()) return res;

    // Collect maximal runs of positions that cannot start a valid UTF-8
    // sequence. Fast path: no runs at all -> already valid UTF-8.
    struct run_t { size_t start; size_t len; };
    std::vector<run_t> runs;
    size_t total_run_bytes = 0;

    for (size_t i = 0; i < s.size(); ) {
        size_t l = utf8_seq_len(s, i);
        if (l > 0) {
            i += l;
        } else {
            size_t j = i;
            while (j < s.size() && utf8_seq_len(s, j) == 0) j++;
            runs.push_back({i, j - i});
            total_run_bytes += (j - i);
            i = j;
        }
    }

    if (runs.empty()) {
        res.text = s;
        return res;
    }

    // Score every candidate encoding over ALL runs at once: per-run scoring is
    // too noisy for short fragments, a document is almost always in one legacy
    // encoding.
    double scores[3] = {0.0, 0.0, 0.0};
    for (const auto & r : runs) {
        for (size_t c = 0; c < 3; c++) {
            const uint32_t * map = kCandidates[c].map;
            double score = 0.0;
            for (size_t k = 0; k < r.len; k++) {
                score += char_weight(map[(unsigned char) s[r.start + k]]);
            }
            scores[c] += score;
        }
    }

    int best = 0;
    for (int c = 1; c < 3; c++) {
        if (scores[c] > scores[best]) best = c;
    }

    // Plausibility threshold: real Russian text averages well above 2.5 per
    // byte under its own encoding; random/binary data stays below it under
    // every candidate.
    bool accept = scores[best] >= 2.5 * (double) total_run_bytes;
    if (!accept) {
        for (size_t i = 0; i < s.size(); ) {
            size_t l = utf8_seq_len(s, i);
            if (l > 0) {
                res.text.append(s, i, l);
                i += l;
            } else {
                size_t j = i;
                while (j < s.size() && utf8_seq_len(s, j) == 0) j++;
                for (size_t k = i; k < j; k++) append_utf8(res.text, 0xFFFD);
                i = j;
            }
        }
        return res;
    }

    const uint32_t * map = kCandidates[best].map;
    size_t pos = 0;
    for (const auto & r : runs) {
        res.text.append(s, pos, r.start - pos);
        for (size_t k = 0; k < r.len; k++) {
            uint32_t cp = map[(unsigned char) s[r.start + k]];
            append_utf8(res.text, cp == 0 ? 0xFFFD : cp);
        }
        pos = r.start + r.len;
    }
    res.text.append(s, pos, s.size() - pos);

    res.reencoded = true;
    res.encoding = kCandidates[best].name;
    return res;
}

size_t utf8_safe_cut(const std::string & s, size_t pos) {
    // Advance past continuation bytes (10xxxxxx) so the cut lands on a codepoint
    // boundary; a UTF-8 sequence is at most 4 bytes, so 3 steps suffice.
    if (pos == 0 || pos >= s.size()) {
        return pos;
    }
    size_t limit = pos + 3 < s.size() ? pos + 3 : s.size();
    while (pos < limit && ((unsigned char) s[pos] & 0xC0) == 0x80) {
        pos++;
    }
    return pos;
}
