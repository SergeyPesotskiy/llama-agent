// Returns the length of a valid UTF-8 sequence starting at s[i..], or 0 if none.
size_t utf8_seq_len(const std::string & s, size_t i) {
    const unsigned char * p = reinterpret_cast<const unsigned char *>(s.data()) + i;
    const size_t n = s.size() - i;
    uint32_t cp;
    size_t len;
    if (p[0] < 0x80) return 1; // ascii
    if ((p[0] & 0xE0) == 0xC0) {
        len = 2; cp = p[0] & 0x1F;
    } else if ((p[0] & 0xF0) == 0xE0) {
        len = 3; cp = p[0] & 0x0F;
    } else if ((p[0] & 0xF8) == 0xF0) {
        len = 4; cp = p[0] & 0x07;
    } else {
        return 0; // stray continuation byte or invalid lead (0xC0/0xC1 overlong, > 0xF4)
    }
    if (len > n) return 0;
    for (size_t k = 1; k < len; k++) {
        if ((p[k] & 0xC0) != 0x80) return 0;
        cp = (cp << 6) | (p[k] & 0x3F);
    }
    // overlong encodings
    if (len == 2 && cp < 0x80) return 0;
    if (len == 3 && cp < 0x800) return 0;
    if (len == 4 && cp < 0x10000) return 0;
    // surrogates and out of range
    if (cp >= 0xD800 && cp <= 0xDFFF) return 0;
    if (cp > 0x10FFFF) return 0;
    return len;
}

void append_utf8(std::string & out, uint32_t cp) {
    if (cp < 0x80) {
        out += (char) cp;
    } else if (cp < 0x800) {
        out += (char) (0xC0 | (cp >> 6));
        out += (char) (0x80 | (cp & 0x3F));
    } else if (cp < 0x10000) {
        out += (char) (0xE0 | (cp >> 12));
        out += (char) (0x80 | ((cp >> 6) & 0x3F));
        out += (char) (0x80 | (cp & 0x3F));
    } else {
        out += (char) (0xF0 | (cp >> 18));
        out += (char) (0x80 | ((cp >> 12) & 0x3F));
        out += (char) (0x80 | ((cp >> 6) & 0x3F));
        out += (char) (0x80 | (cp & 0x3F));
    }
}

