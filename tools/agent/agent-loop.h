// Stop reasons for the agent loop
enum class agent_stop_reason {
    COMPLETED,        // Model finished without tool calls
    MAX_ITERATIONS,   // Hit iteration limit
    USER_CANCELLED,   // User interrupted
    AGENT_ERROR,      // Error occurred (not ERROR due to Windows macro conflict)
    TOKEN_BUDGET_EXCEEDED, // max_generate_tokens budget exhausted (subagents)
};

// Configuration for the agent
struct agent_config {
    int max_iterations = 0;  // 0 = unlimited
    int tool_timeout_ms = 120000;
    std::string working_dir;
    bool verbose = false;
    bool yolo_mode = false;  // Skip all permission prompts

    // Skills configuration (agentskills.io spec)
    bool enable_skills = true;
    std::vector<std::string> skills_search_paths;  // Additional search paths
    std::string skills_prompt_section;             // Pre-generated XML for prompt injection

    // AGENTS.md configuration (agents.md spec)
    bool enable_agents_md = true;
    std::string agents_md_prompt_section;          // Pre-generated XML for prompt injection

    // Context compaction
    compaction_settings compaction;

    // Inference backend scheduling. -1 lets the backend/server choose.
    int32_t inference_id_slot = -1;

    // Subagents (task tool). Opt-in via --subagents / --max-subagent-depth N.
    bool subagents_enabled = false;  // task tool available
    int max_subagent_depth = 0;      // 0 = disabled, 1-5 = nesting depth
    bool subagent_own_slot = false;  // subagents get their own server slot (needs --parallel >= 2)

    // Generated-token budget for this loop. 0 = off. Set per subagent via the
    // task tool's "max_tokens" parameter; when the loop's generated-token
    // counter exceeds it, the loop stops with TOKEN_BUDGET_EXCEEDED.
    int64_t max_generate_tokens = 0;

    // Wrap tool results in <external_data untrusted="true"> tags and add the
    // matching system-prompt line. Opt-in via --tool-output-guard (default off;
    // off state is byte-identical to the historical prompt protocol).
    bool tool_output_guard = false;
};

// Result from running the agent loop
struct agent_loop_result {
    agent_stop_reason stop_reason;
    std::string final_response;
    int iterations = 0;
};

// Session-level statistics for token tracking.
// The int fields are atomic: the owning agent_loop updates them in
// accumulate_stats() (main thread) while background subagent threads update
// the subagent_* / total_* fields through a raw pointer (subagent-runner.cpp).
// The double fields are only written by the owning loop's thread.
struct session_stats {
    std::atomic<int32_t> total_input{0};      // Total prompt tokens processed
    std::atomic<int32_t> total_output{0};     // Total tokens generated
    std::atomic<int32_t> total_cached{0};     // Total tokens served from KV cache
    double total_prompt_ms = 0;    // Total prompt evaluation time
    double total_predicted_ms = 0; // Total generation time

    // Subagent breakdown (for /stats display)
    std::atomic<int32_t> subagent_input{0};   // Prompt tokens processed by subagents
    std::atomic<int32_t> subagent_output{0};  // Tokens generated by subagents
    std::atomic<int32_t> subagent_cached{0};  // Subagent tokens served from KV cache
    std::atomic<int32_t> subagent_count{0};   // Number of subagent runs

    session_stats() = default;
    // C++17 std::atomic is not copyable, but this struct is passed by value
    // to the TUI (tui_event / tui_footer_state) and reset via copy-assign.
    session_stats(const session_stats & o)
        : total_input(o.total_input.load(std::memory_order_relaxed)),
          total_output(o.total_output.load(std::memory_order_relaxed)),
          total_cached(o.total_cached.load(std::memory_order_relaxed)),
          total_prompt_ms(o.total_prompt_ms),
          total_predicted_ms(o.total_predicted_ms),
          subagent_input(o.subagent_input.load(std::memory_order_relaxed)),
          subagent_output(o.subagent_output.load(std::memory_order_relaxed)),
          subagent_cached(o.subagent_cached.load(std::memory_order_relaxed)),
          subagent_count(o.subagent_count.load(std::memory_order_relaxed)) {}
    session_stats & operator=(const session_stats & o) {
        total_input.store(o.total_input.load(std::memory_order_relaxed), std::memory_order_relaxed);
        total_output.store(o.total_output.load(std::memory_order_relaxed), std::memory_order_relaxed);
        total_cached.store(o.total_cached.load(std::memory_order_relaxed), std::memory_order_relaxed);
        total_prompt_ms = o.total_prompt_ms;
        total_predicted_ms = o.total_predicted_ms;
        subagent_input.store(o.subagent_input.load(std::memory_order_relaxed), std::memory_order_relaxed);
        subagent_output.store(o.subagent_output.load(std::memory_order_relaxed), std::memory_order_relaxed);
        subagent_cached.store(o.subagent_cached.load(std::memory_order_relaxed), std::memory_order_relaxed);
        subagent_count.store(o.subagent_count.load(std::memory_order_relaxed), std::memory_order_relaxed);
        return *this;
    }
};

// Event types for streaming API
enum class agent_event_type {
    TEXT_DELTA,           // Streaming LLM token output
    REASONING_DELTA,      // Streaming reasoning/thinking content
    TOOL_CALL_DELTA,      // Streaming tool-call argument output
    TOOL_START,           // Tool execution starting
    TOOL_RESULT,          // Tool execution completed
    PERMISSION_REQUIRED,  // Permission required - waiting for response
    PERMISSION_RESOLVED,  // Permission was granted or denied
    ITERATION_START,      // New iteration starting
    COMPACTION_COMPLETED, // Context compaction finished
    COMPLETED,            // Agent finished successfully
    ERROR,                // Error occurred
};

// Event data for streaming API
struct agent_event {
    agent_event_type type;
    json data;  // Event-specific payload

    // Convenience constructors
    static agent_event text_delta(const std::string & content) {
        return {agent_event_type::TEXT_DELTA, {{"content", content}}};
    }

    static agent_event reasoning_delta(const std::string & content) {
        return {agent_event_type::REASONING_DELTA, {{"content", content}}};
    }

    static agent_event tool_start(const std::string & name, const std::string & args) {
        return {agent_event_type::TOOL_START, {{"name", name}, {"args", args}}};
    }

    static agent_event tool_call_delta(size_t index, const std::string & name, const std::string & args_delta) {
        return {agent_event_type::TOOL_CALL_DELTA, {
            {"index", index},
            {"name", name},
            {"args_delta", args_delta}
        }};
    }

    static agent_event tool_result(const std::string & name, bool success,
                                    const std::string & output, int64_t duration_ms,
                                    const std::string & error = "", bool no_truncate = false) {
        return {agent_event_type::TOOL_RESULT, {
            {"name", name},
            {"success", success},
            {"output", output},
            {"error", error},
            {"no_truncate", no_truncate},
            {"duration_ms", duration_ms}
        }};
    }

    static agent_event permission_required(const std::string & request_id,
                                            const std::string & tool_name,
                                            const std::string & description,
                                            const std::string & details,
                                            bool is_dangerous) {
        return {agent_event_type::PERMISSION_REQUIRED, {
            {"request_id", request_id},
            {"tool", tool_name},
            {"description", description},
            {"details", details},
            {"dangerous", is_dangerous}
        }};
    }

    static agent_event permission_resolved(const std::string & request_id, bool allowed) {
        return {agent_event_type::PERMISSION_RESOLVED, {
            {"request_id", request_id},
            {"allowed", allowed}
        }};
    }

    static agent_event iteration_start(int iteration, int max_iterations) {
        return {agent_event_type::ITERATION_START, {
            {"iteration", iteration},
            {"max_iterations", max_iterations}
        }};
    }

    static agent_event completed(agent_stop_reason reason, const session_stats & stats, int32_t last_prompt_tokens = 0) {
        std::string reason_str;
        switch (reason) {
            case agent_stop_reason::COMPLETED:      reason_str = "completed"; break;
            case agent_stop_reason::MAX_ITERATIONS: reason_str = "max_iterations"; break;
            case agent_stop_reason::USER_CANCELLED: reason_str = "user_cancelled"; break;
            case agent_stop_reason::AGENT_ERROR:    reason_str = "error"; break;
            case agent_stop_reason::TOKEN_BUDGET_EXCEEDED: reason_str = "token_budget_exceeded"; break;
        }
        return {agent_event_type::COMPLETED, {
            {"reason", reason_str},
            {"stats", {
                {"input_tokens", stats.total_input.load()},
                {"output_tokens", stats.total_output.load()},
                {"cached_tokens", stats.total_cached.load()},
                {"total_predicted_ms", stats.total_predicted_ms},
                {"last_prompt_tokens", last_prompt_tokens}
            }}
        }};
    }

    static agent_event error(const std::string & message) {
        return {agent_event_type::ERROR, {{"message", message}}};
    }

    static agent_event compaction_completed(int32_t messages_kept) {
        return {agent_event_type::COMPACTION_COMPLETED, {{"messages_kept", messages_kept}}};
    }
};

// Callback type for streaming events
using agent_event_callback = std::function<void(const agent_event &)>;

// Callback reporting a tool call from a subagent to its parent display
// (tool name, truncated argument summary, elapsed ms)
using tool_call_callback = std::function<void(const std::string & tool_name,
                                              const std::string & args_summary,
                                              int elapsed_ms)>;

// The main agent loop class
class agent_loop {
public:
    // Standard constructor
    agent_loop(inference_backend & backend,
               const agent_config & config,
               std::atomic<bool> & is_interrupted,
               session_file * sf = nullptr,
               const loaded_session * resume = nullptr);

    // Subagent constructor: restricted tool set, custom system prompt, no skills/AGENTS.md.
    // allowed_tools empty = all tools; bash_patterns non-empty = read-only bash filtering.
    // subagent_depth is the nesting depth (parent's depth + 1). on_tool_call reports each
    // tool invocation to the parent for display. Shares the parent's inference backend.
    // extra_interrupt: optional per-task interrupt flag (subagent cancel /
    // timeout). The loop stops when (is_interrupted || *extra_interrupt).
    agent_loop(inference_backend & backend,
               const agent_config & config,
               std::atomic<bool> & is_interrupted,
               const std::set<std::string> & allowed_tools,
               const std::vector<std::string> & bash_patterns,
               const std::string & custom_system_prompt,
               int subagent_depth,
               tool_call_callback on_tool_call,
               std::atomic<bool> * extra_interrupt = nullptr);

    // Run the agent loop with user content.
    // content can be a plain string or a JSON array of content blocks
    // (e.g. [{type:"text",text:"..."}, {type:"image_url",image_url:{url:"data:..."}}])
    agent_loop_result run(const json & user_content);

    // Run the agent loop with streaming events via callback.
    // content can be a plain string or a JSON array of content blocks.
    // The callback is called for each event (text deltas, tool calls, permissions, etc.)
    // should_stop is polled to check if the client wants to abort
    // async_perms: optional async permission manager for non-blocking permission handling
    agent_loop_result run_streaming(
        const json & user_content,
        agent_event_callback on_event,
        std::function<bool()> should_stop = nullptr,
        permission_manager_async * async_perms = nullptr);

    // Clear conversation history
    void clear();

    // Add a message to the conversation history without triggering generation.
    // Used by the REPL for injecting user-executed shell command output (! prefix).
    void add_context_message(const std::string & role, const std::string & content);

    // Force context compaction regardless of threshold.
    // Returns true if compaction was performed.
    bool compact();

    // Get current messages (for debugging)
    const json & get_messages() const { return messages_; }

    // Get session statistics
    const session_stats & get_stats() const { return stats_; }

private:
    // Build a backend-neutral inference request from the agent's messages and tools.
    // Strips image_url blocks when has_vision is false.
    inference_request build_inference_request(
        const std::vector<common_chat_tool> & chat_tools,
        bool parse_tool_calls = true);

    // Generate a completion and get the parsed response with tool calls
    inference_result generate_completion();

    // Generate completion with streaming events via callback
    inference_result generate_completion_streaming(
        agent_event_callback on_event,
        std::function<bool()> should_stop);

    // Execute a single tool call
    tool_result execute_tool_call(const common_chat_tool_call & call);

    // Execute tool call with async permission handling (for streaming API)
    // Emits PERMISSION_REQUIRED events and waits for async responses
    tool_result execute_tool_call_async(
        const common_chat_tool_call & call,
        agent_event_callback on_event,
        permission_manager_async & async_perms,
        std::function<bool()> should_stop);

    // Format tool result as message
    void add_tool_result_message(const std::string & tool_name,
                                  const std::string & call_id,
                                  const tool_result & result);

    // Build assistant message JSON from parsed completion
    json build_assistant_msg(const common_chat_msg & parsed, int iteration);

    // Two-phase tool execution used by the concurrent task-call batch: the
    // permission/prompt phase always runs sequentially on the loop thread,
    // only the execution phase moves to worker threads.
    struct prepared_tool_call {
        bool proceed = false;   // false => return 'early' without executing
        json args;              // parsed arguments (when proceed)
        tool_result early;      // permission denial / parse error
    };

    prepared_tool_call prepare_tool_call_async(const common_chat_tool_call & call,
                                               agent_event_callback on_event,
                                               permission_manager_async & async_perms,
                                               std::function<bool()> should_stop);
    prepared_tool_call prepare_tool_call(const common_chat_tool_call & call);
    tool_result run_prepared_tool_call(const common_chat_tool_call & call, const json & args,
                                       bool quiet_display = false);

    // True when an assistant turn requests >= 2 subagent runs (concurrent
    // task-call batch); other tool calls keep running sequentially.
    static bool should_batch_task_calls(const std::vector<common_chat_tool_call> & calls);

    // Accumulate timing stats from a completion
    void accumulate_stats(const inference_result & result);

    // Context compaction: summarize old messages when context gets large
    bool try_compact();
    bool do_compact(int32_t effective_keep);
    std::string generate_summary(const json & messages_to_summarize,
                                  const std::string & previous_summary);

    inference_backend & backend_;
    agent_config config_;
    std::atomic<bool> & is_interrupted_;

    // Per-task interrupt flag (subagent cancel/timeout); null for the main loop.
    // Interruption is checked as (parent || extra) via interrupt_requested().
    std::atomic<bool> * extra_interrupt_ = nullptr;

    bool interrupt_requested() const {
        return is_interrupted_.load() || (extra_interrupt_ && extra_interrupt_->load());
    }

    json messages_;
    permission_manager permission_mgr_;
    tool_context tool_ctx_;
    session_stats stats_;

    // Subagent state (main agent: allowed_tools_ empty, is_subagent_ false)
    std::set<std::string> allowed_tools_;      // Tool whitelist; empty = all tools
    std::vector<std::string> bash_patterns_;   // Read-only bash prefixes; empty = no filter
    tool_call_callback on_tool_call_;          // Report tool calls to parent display
    bool is_subagent_ = false;                 // Suppress main-agent console output

    // Compaction state
    int32_t     last_prompt_tokens_ = 0;
    bool        last_completion_overflowed_ = false;

    std::string previous_summary_;

    // Session persistence
    session_file * session_file_ = nullptr;
};
